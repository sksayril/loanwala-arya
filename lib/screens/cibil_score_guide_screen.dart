                      'People with good scores often get cheaper interest rates on home loans, car loans, and personal loans.',
                ),
                _subheading('Example:'),
                _exampleBox(
                  'Good score → 8–9% interest\nLow score → 12–15% interest',
                ),
                _p('This can save lakhs of rupees over time.'),
                _bulletSection(
                  title: '💳 Easy Credit Card Approval',

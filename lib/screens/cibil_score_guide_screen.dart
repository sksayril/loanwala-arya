                _scoreRow('🟡', '650 – 699', 'Average', const Color(0xFFEAB308)),
                _scoreRow('🟢', '700 – 749', 'Good', const Color(0xFF22C55E)),
                _scoreRow('⭐', '750 – 900', 'Excellent', const Color(0xFF8B5CF6)),
                _p(
                  'The higher your score, the easier it is to get loans.',
